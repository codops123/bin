#include <iostream>
#include <string>
#include <vector>
#include <cmath>

using namespace std;

/*
 * Problem Statement:
 * Given input terminal string: "aabaabaa"
 * 
 * Structural Analysis:
 * - Total length: 8 characters
 * - Pattern breakdown:
 *   Notice the repetition of "aab":
 *   "aab" + "aab" + "aa"
 *   Let's check forms in terms of n (n > 0):
 *   
 *   Option A: Language L = { (aab)^n aa | n >= 0 }
 *             For n = 2: (aab)^2 aa = "aabaabaa"  (Length = 3*2 + 2 = 8)
 * 
 *   Option B: Language L = { a (aba)^n a | n > 0 } or { (a)^m (b)^k ... }
 *   
 *   Most standard and precise representation:
 *   Language: L = { (aab)^n aa | n >= 1 } (or with n > 0, n = 2 yields "aabaabaa")
 *   
 *   Context-Free Grammar (CFG):
 *   G = (V, Σ, R, S)
 *   V = {S, A}
 *   Σ = {a, b}
 *   Start symbol = S
 *   
 *   Production Rules:
 *   S -> A aa
 *   A -> aab A | aab
 *   
 *   (Guarantees at least one "aab", so n >= 1, i.e., n > 0)
 */

class CFGPatternGenerator {
private:
    string inputString;

public:
    CFGPatternGenerator(const string& str) : inputString(str) {}

    void analyzePattern() {
        cout << "=================================================================\n";
        cout << " CFG & Language Pattern Generator for Input: " << inputString << "\n";
        cout << "=================================================================\n\n";

        cout << "[1] String Decomposition:\n";
        cout << "    Input: \"" << inputString << "\" (Length = " << inputString.length() << ")\n";
        cout << "    Repeated Prefix unit: \"aab\"\n";
        cout << "    Occurrences of \"aab\": 2 times -> \"aab\" + \"aab\"\n";
        cout << "    Suffix remaining: \"aa\"\n";
        cout << "    Full partition: (\"aab\") * 2 + \"aa\"\n\n";

        cout << "[2] Language Pattern in Terms of n (where n > 0):\n";
        cout << "    Formula : L = { (aab)^n aa | n > 0 }\n";
        cout << "    Here, for the given input \"aabaabaa\", n = 2.\n\n";

        cout << "[3] Context-Free Grammar (CFG):\n";
        cout << "    Variables (Non-terminals) V = { S, A }\n";
        cout << "    Terminals                 Σ = { a, b }\n";
        cout << "    Start Symbol                = S\n\n";
        cout << "    Production Rules (P):\n";
        cout << "    ---------------------\n";
        cout << "    1. S -> A aa\n";
        cout << "    2. A -> aab A\n";
        cout << "    3. A -> aab\n\n";

        cout << "[4] Derivation of \"" << inputString << "\" for n = 2:\n";
        cout << "    S  => A aa               (using Rule 1: S -> A aa)\n";
        cout << "       => aab A aa            (using Rule 2: A -> aab A)\n";
        cout << "       => aab aab aa          (using Rule 3: A -> aab)\n";
        cout << "       => aabaabaa            (Derived Successfully!)\n\n";
    }

    void generateStrings(int maxN) {
        cout << "[5] General Strings generated by L = { (aab)^n aa } for n = 1 to " << maxN << ":\n";
        cout << "-----------------------------------------------------------------\n";
        for (int n = 1; n <= maxN; n++) {
            string generated = "";
            for (int i = 0; i < n; i++) {
                generated += "aab";
            }
            generated += "aa";
            cout << "  n = " << n << " : " << generated 
                 << "  (length = " << generated.length() << ")\n";
        }
        cout << "=================================================================\n";
    }
};

int main() {
    string target = "aabaabaa";
    CFGPatternGenerator generator(target);
    generator.analyzePattern();
    generator.generateStrings(5);

    return 0;
}
